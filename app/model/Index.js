const mongoose = require('mongoose')

/* ====================================================================
    Schema
==================================================================== */

const indexSchema = mongoose.Schema({
    name: {
        type: String,
        required: true
    },
    index: {
        type: String,
        required: true
    }
})

/* ====================================================================
    Model
==================================================================== */

const Index = mongoose.model('Index', indexSchema, 'indexes')

/* ====================================================================
    Export
==================================================================== */

module.exports = Index